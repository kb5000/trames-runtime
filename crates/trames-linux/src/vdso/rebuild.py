"""Rebuild checked-in freestanding AArch64 code; not needed by Cargo builds."""
import argparse
from pathlib import Path
import struct
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--clang', default='clang')
    parser.add_argument('--linker')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    sysroot = Path(subprocess.check_output(['rustc', '--print', 'sysroot'], text=True).strip())
    host = subprocess.check_output(['rustc', '-vV'], text=True).split('host: ')[1].splitlines()[0]
    linker = args.linker or str(sysroot / 'lib/rustlib' / host / 'bin/rust-lld')

    with tempfile.TemporaryDirectory() as temporary:
        output = Path(temporary)
        obj, elf = output / 'vdso.o', output / 'vdso.elf'
        subprocess.run([args.clang, '--target=aarch64-linux-gnu', '-c',
                        str(root / 'aarch64.S'), '-o', str(obj)], check=True)
        subprocess.run([linker, '-flavor', 'gnu', '-m', 'aarch64elf', '-Ttext=0x600',
                        '--image-base=0', '--defsym=vdso_data=0x1000', '-e',
                        '__kernel_clock_gettime', str(obj), '-o', str(elf)], check=True)
        data = elf.read_bytes()

    shoff = struct.unpack_from('<Q', data, 40)[0]
    size, count, strings_index = struct.unpack_from('<HHH', data, 58)
    sections = [struct.unpack_from('<IIQQQQIIQQ', data, shoff + i * size) for i in range(count)]

    def contents(section):
        return data[section[4]:section[4] + section[5]]

    def name_at(strings, offset):
        return strings[offset:].split(b'\0', 1)[0].decode()

    names = contents(sections[strings_index])
    text = next(section for section in sections if name_at(names, section[0]) == '.text')
    assert text[3] == 0x600, 'vDSO ELF entry layout changed'
    code = contents(text)
    assert len(code) % 4 == 0 and 0x600 + len(code) <= 4096
    symbols = []
    for section in sections:
        if section[1] != 2:  # SHT_SYMTAB
            continue
        strings = contents(sections[section[6]])
        for at in range(section[4], section[4] + section[5], section[9]):
            name, _, _, _, value, length = struct.unpack_from('<IBBHQQ', data, at)
            name = name_at(strings, name)
            if name.startswith('__kernel_'):
                symbols.append((name, value, length))
    symbols.sort(key=lambda symbol: symbol[1])
    assert len(symbols) == 4 and symbols[0][1] == 0x600
    lines = [
        '// SPDX-License-Identifier: GPL-3.0-or-later',
        '// Generated by vdso/rebuild.py from aarch64.S; do not edit.',
        'pub(super) const SYMBOLS: &[(&str, u64, u64)] = &[',
    ]
    lines += [f'    ("{name}", {value:#x}, {size}),' for name, value, size in symbols]
    lines += ['];', 'pub(super) const CODE: &[u32] = &[']
    for i in range(0, len(code), 16):
        words = struct.unpack('<' + 'I' * (len(code[i:i + 16]) // 4), code[i:i + 16])
        lines.append('    ' + ', '.join(f'0x{word:08x}' for word in words) + ',')
    lines += ['];', '']
    (root / 'code.rs').write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
